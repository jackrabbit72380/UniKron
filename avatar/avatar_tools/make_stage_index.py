#!/usr/bin/env python3
"""Writes avatar/StageIndex.qml - how many frames each baked set has, and which
frame looks at the camera.

The editor cannot list a directory at runtime (the same reason AssetIndex.qml
exists), so AvatarStage3D used to find a set's length by asking Qt for
frame_00.png, frame_01.png, ... until one failed to load. That costs one failed
load per set switch - one line in the log - and, worse, it is asynchronous: the
stage only knows `frameCount` after the last probe comes back, so for the first
few frames of every switch it was still showing frame 0. For a 20-frame
whole-body turntable frame 0 is the avatar's *back* (measured: see the comment on
`restFrame` in AvatarStage3D.qml), which is why switching items could flash the
back of the avatar's head before the stage caught up.

Every set was baked by one of two scripts, and each one's first frame is known
from its own render loop:

    bake_pack_turntables.bake_one   yaw = pi + 2*pi*i/frames
                                    -> frame 0 is the front (a half turn)
    bake_turntable.main             yaw = radians(start) + 2*pi*i/frames
                                    start defaults to 0, the back
                                    -> the front is frame frames/2

The 6-frame sets in this project are the item bakes (bake_pack_turntables, and
rebake_stale.py calls bake_one with frames=6); the longer sets are whole-body
turntables (the 20-frame stock sets and hand-drawn hair, the 18-frame
hair_bun_red). That boundary is a fact about the two bakers, not a guess, and the
three sets that were read frame by frame on 2026-11-19 are checked below: if the
rule ever stops matching them the script fails instead of writing a wrong index.

    python3 make_stage_index.py           # rewrite StageIndex.qml
    python3 make_stage_index.py --check   # nonzero if it is out of date
"""

import argparse
import glob
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
AVATAR = os.path.dirname(HERE)
STAGE = os.path.join(AVATAR, "assets", "3d")
INDEX = os.path.join(AVATAR, "StageIndex.qml")

# Sets baked by bake_pack_turntables.bake_one: its first frame is the front.
ITEM_FRAMES = 6

FRAME = re.compile(r"^frame_(\d+)\.png$")
ANIMATED = re.compile(r"^yaw_(\d+)_pose_(\d+)\.png$")

# Read frame by frame on 2026-11-19, the three sets the QML's comment cites.
# (frames, front) as measured, not as computed.
MEASURED = {
    "turntable/jacket-with-sweater": (6, 0),
    "turntable/hair_long_blond": (20, 10),
    "turntable/hair_bun_red": (18, 9),
}

HEADER = """\
import QtQuick 2.15

// Generated by avatar_tools/make_stage_index.py - do not edit by hand.
// One entry per baked frame set under assets/3d, keyed by the variant string the
// editor hands the stage ("turntable/<stem>", "turntable_female", ...).
//   frames  how many frame_NN.png files the set has
//   front   the frame that looks at the camera, from the baker's own yaw loop
//           (see the script: item bakes open on the front, whole-body turn-
//           tables open on the back, so theirs is frames/2)
// Re-run after baking: bake_pack_turntables.py and rebake_stale.py do it for you.
QtObject {
"""


def front_frame(count):
    """The frame that faces the camera, from the baker that wrote the set."""
    return 0 if count <= ITEM_FRAMES else count // 2


def scan():
    """Every set under assets/3d as { key: {"frames": n, "front": f} }."""
    sets = {}
    problems = []
    for dirpath, dirnames, filenames in os.walk(STAGE):
        dirnames[:] = sorted(d for d in dirnames if d != "animated")
        numbers = []
        for name in filenames:
            m = FRAME.match(name)
            if m:
                numbers.append(int(m.group(1)))
        if not numbers:
            continue
        rel = os.path.relpath(dirpath, STAGE).replace(os.sep, "/")
        numbers.sort()
        if numbers != list(range(len(numbers))):
            # A gap means the set was interrupted mid-bake; the stage's probe
            # would stop at the gap and the spin would wrap early.
            problems.append("%s: frames %d..%d with %d gap(s)"
                            % (rel, numbers[0], numbers[-1],
                               numbers[-1] + 1 - len(numbers)))
        sets[rel] = {"frames": len(numbers), "front": front_frame(len(numbers))}
    return dict(sorted(sets.items())), problems


def scan_animated():
    """yaw/pose counts of the animated set, or None when it was not baked."""
    yaws, poses = set(), set()
    for path in glob.glob(os.path.join(STAGE, "animated", "*.png")):
        m = ANIMATED.match(os.path.basename(path))
        if m:
            yaws.add(int(m.group(1)))
            poses.add(int(m.group(2)))
    if not yaws or not poses:
        return None
    # bake_animated.py writes what the set is a picture of. Without it the stage
    # cannot tell whether the player is still wearing that outfit, so it falls
    # back to the static turntable.
    variant = ""
    meta = os.path.join(STAGE, "animated", "set.json")
    if os.path.exists(meta):
        with open(meta, "r", encoding="utf-8") as fh:
            variant = json.load(fh).get("variant", "")
    # The stage indexes 0..count-1, so a gap would step onto a missing file.
    return {"yaws": max(yaws) + 1, "poses": max(poses) + 1, "variant": variant,
            "gaps": (len(yaws) != max(yaws) + 1 or len(poses) != max(poses) + 1)}


def refresh():
    """Write StageIndex.qml and return (sets, frames). The bakers call this."""
    sets, _problems = scan()
    animated = scan_animated()
    with open(INDEX, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(render(sets, animated))
    return len(sets), sum(entry["frames"] for entry in sets.values())


def render(sets, animated):
    lines = [HEADER]
    lines.append('    // %d sets, %d frames.\n'
                 % (len(sets), sum(e["frames"] for e in sets.values())))
    lines.append("    readonly property var sets: {\n")
    for key, entry in sets.items():
        lines.append('        "%s": { "frames": %d, "front": %d },\n'
                     % (key, entry["frames"], entry["front"]))
    lines.append("    }\n")
    if animated:
        lines.append("\n    // assets/3d/animated: yawCount angles crossed with poseCount poses.\n")
        lines.append('    readonly property var animated: { "yaws": %d, "poses": %d, "variant": "%s" }\n'
                     % (animated["yaws"], animated["poses"], animated["variant"]))
    else:
        lines.append("\n    readonly property var animated: null\n")
    lines.append("}\n")
    return "".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true",
                    help="do not write; exit 1 if StageIndex.qml is out of date")
    args = ap.parse_args(argv)

    sets, problems = scan()
    animated = scan_animated()
    if animated and animated["gaps"]:
        problems.append("animated: yaw/pose numbering has a gap")

    # Anchor the front-frame rule to the sets that were actually read.
    bad = 0
    for key, (frames, front) in MEASURED.items():
        got = sets.get(key)
        if got is None:
            print("MEASURED set missing: %s" % key)
            bad += 1
        elif (got["frames"], got["front"]) != (frames, front):
            print("MEASURED %s: expected %d frames front %d, index says %d front %d"
                  % (key, frames, front, got["frames"], got["front"]))
            bad += 1

    text = render(sets, animated)
    current = None
    if os.path.exists(INDEX):
        with open(INDEX, "r", encoding="utf-8") as fh:
            current = fh.read()

    if args.check:
        if current != text:
            print("StageIndex.qml is out of date: re-run make_stage_index.py")
            bad += 1
    else:
        with open(INDEX, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)

    for problem in problems:
        print("  " + problem)
    shapes = {}
    for entry in sets.values():
        shapes[entry["frames"]] = shapes.get(entry["frames"], 0) + 1
    print("%s StageIndex.qml: %d sets, %d frames (%s)%s"
          % ("checked" if args.check else "wrote", len(sets),
             sum(e["frames"] for e in sets.values()),
             ", ".join("%d x %d" % (n, f) for f, n in sorted(shapes.items())),
             ", animated %dx%d" % (animated["yaws"], animated["poses"]) if animated else ""))
    return 1 if (bad or problems) else 0


if __name__ == "__main__":
    sys.exit(main())
