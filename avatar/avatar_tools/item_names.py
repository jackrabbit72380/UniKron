"""Write avatar/ItemNames.qml: art-file stem -> the retail asset it was baked from.

The wardrobe's art files are named for colours (`tee_blue`, `hoodie_grey`), but
every one of them was baked from a real pack asset recorded in `items_3d.json`
(shirts, trousers, shoes) or `outfits.json` (hairstyles). The editor should show
the retail name, not the art stem, so this maps one to the other and refuses to
write a name that is not in the pack.

    python3 item_names.py            # writes ../ItemNames.qml
"""

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), "ItemNames.qml")


def load(name):
    with open(os.path.join(HERE, name), "r", encoding="utf-8") as fh:
        return json.load(fh)


def main():
    catalog = load("asset_catalog.json")
    pack = {entry["name"]: entry for entry in catalog["assets"]}

    mapping = {}
    unknown = []
    for stem, entry in load("items_3d.json").items():
        if stem.startswith("_"):
            continue
        asset = entry.get("asset")
        if asset in pack:
            mapping[stem] = asset
        else:
            unknown.append((stem, asset))
    for stem, entry in load("outfits.json").items():
        if stem.startswith("_"):
            continue
        hair = entry.get("hair")
        if hair in pack:
            mapping[stem] = hair
        else:
            unknown.append((stem, hair))

    for stem, asset in unknown:
        print("not in pack: %s -> %r" % (stem, asset))

    lines = [
        "import QtQuick 2.15",
        "",
        "// Generated by avatar_tools/item_names.py - do not edit by hand.",
        "// Art-file stem -> the retail AvatarAssetPack asset that stem was baked",
        "// from. Every name here was checked against the pack's records.",
        "QtObject {",
        "    readonly property var names: ({",
    ]
    entries = sorted(mapping.items())
    for index, (stem, asset) in enumerate(entries):
        comma = "," if index + 1 < len(entries) else ""
        lines.append('        "%s": "%s"%s' % (stem, asset.replace('"', '\\"'), comma))
    lines += [
        "    })",
        "",
        "    // \"tee_blue.png\" -> \"Male Power Tee\", or \"\" when the art is not a",
        "    // pack asset (the skin-tone bodies, for instance).",
        "    function of(fileName) {",
        "        var stem = String(fileName || \"\").replace(/\\.png$/i, \"\")",
        "        return names[stem] !== undefined ? names[stem] : \"\"",
        "    }",
        "}",
        "",
    ]
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print("wrote %s with %d names (%d unknown)" % (OUT, len(mapping), len(unknown)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
