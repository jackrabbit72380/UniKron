"""Write `Colours.qml` and `PackMasks.qml` from the extracted data.

`xex_palettes.py` reads the nine colour tables out of `avatareditor.xex` and writes
`colour_palettes.json`; `bake_pack_face.py --mask` writes one tint mask per face
item into `pack_plates_mask/`. The editor needs both at run time, and neither can be
read from disk by QML, so this turns them into two generated QML objects - the same
way `bake_pack_thumbs.py` writes `PackPlates.qml`.

    python3 make_colour_qml.py            # writes ../Colours.qml, ../PackMasks.qml

Exit status is 1 if either source is missing, so a rebuild notices.
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
AVATAR = os.path.dirname(HERE)


def palettes():
    path = os.path.join(AVATAR, "colour_palettes.json")
    if not os.path.exists(path):
        raise SystemExit("%s is missing: run xex_palettes.py first" % path)
    data = json.load(open(path))
    out = []
    for entry in data["slots"]:
        # The tables are stored as ARGB; the editor wants #rrggbb.
        hexes = ['"#%s"' % c[-6:] for c in entry["colours"]]
        out.append((entry["slot"], hexes))
    return out


def masks():
    root = os.path.join(AVATAR, "pack_plates_mask")
    if not os.path.isdir(root):
        raise SystemExit("%s is missing: run bake_pack_face.py --mask first" % root)
    out = []
    for name in sorted(os.listdir(root)):
        folder = os.path.join(root, name)
        if not os.path.isdir(folder):
            continue
        files = sorted(f for f in os.listdir(folder) if f.endswith(".png"))
        if files:
            out.append((name, files))
    return out


def main():
    tables = palettes()
    lines = [
        "import QtQuick 2.15",
        "",
        "// Generated by avatar_tools/make_colour_qml.py - do not edit by hand.",
        "// The colour tables the editor's own binary ships, read out of avatareditor.xex",
        "// at the offsets recorded in avatar_tools/COLOURS.md, as #rrggbb in the order",
        "// the game stores them. The slot names are the XEX's; AvatarEditor.qml maps the",
        "// editor's categories onto them.",
        "QtObject {",
        "    readonly property var palettes: ({",
    ]
    body = []
    for slot, hexes in tables:
        body.append('        "%s": [%s]' % (slot, ", ".join(hexes)))
    lines.append(",\n".join(body))
    lines += ["    })", "}", ""]
    with open(os.path.join(AVATAR, "Colours.qml"), "w") as fh:
        fh.write("\n".join(lines))

    folders = masks()
    lines = [
        "import QtQuick 2.15",
        "",
        "// Generated by avatar_tools/make_colour_qml.py - do not edit by hand.",
        "// One tint mask per face item, baked by `bake_pack_face.py --mask`: RGB is the",
        "// sheet's lighting and alpha its coverage (bake_turntable.render coverage=True),",
        "// so `TintedMask.qml` can multiply it by any palette colour.",
        "QtObject {",
        "    readonly property var folders: [",
    ]
    body = []
    for name, files in folders:
        body.append('        { "id": "%s", "files": [%s] }'
                    % (name, ", ".join('"%s"' % f for f in files)))
    lines.append(",\n".join(body))
    lines += ["    ]", "}", ""]
    with open(os.path.join(AVATAR, "PackMasks.qml"), "w") as fh:
        fh.write("\n".join(lines))

    print("wrote Colours.qml (%d slots: %s)"
          % (len(tables), ", ".join("%s %d" % (s, len(h)) for s, h in tables)))
    print("wrote PackMasks.qml (%d folders, %d masks)"
          % (len(folders), sum(len(f) for _, f in folders)))


if __name__ == "__main__":
    sys.exit(main())
