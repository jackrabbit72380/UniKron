class QuaternionSerializer:
    """Rotation as a quantised axis-angle vector: the same lattice, then sin/cos."""

    def __init__(self, stream):
        self.base = VectorSerializer(stream)

    def read(self, stream):
        x, y, z = self.base.read(stream)
        length = math.sqrt(x * x + y * y + z * z)
        if length < 1e-7:
            return (0.0, 0.0, 0.0, 1.0)
        s = math.sin(length)
        w = math.cos(length)
        k = s / length
        return (x * k, y * k, z * k, w)


def read_skeleton(data=SKELETON_NXE):
    """Joints as dicts: parent, position, rotation (x, y, z, w)."""
    stream = BitStream(data)
    count = stream.read_u32()
    positions = VectorSerializer(stream)
    rotations = QuaternionSerializer(stream)
    joints = []
    for _ in range(count):
        parent = stream.read(8)
        joints.append({
            "parent": parent,
            "position": positions.read(stream),
            "rotation": rotations.read(stream),
        })
    return joints


