# watch_art.ps1 - keeps avatar\AssetIndex.qml in step with the art folders.
#
# Runs hidden in the background: start it once (install_watcher.bat puts it in
# the Startup folder), then dropping art into avatar\assets\30_shoes\ is enough.
# It rewrites the index within a couple of seconds; press F5 in Pegasus to let
# the theme pick up the new file.
#
# Written in PowerShell so it needs nothing installed on Windows.

param(
    [string]$Root = (Split-Path -Parent $PSScriptRoot),
    [switch]$Once          # write the index once and exit, no watching
)

$ErrorActionPreference = "Stop"

$assets = Join-Path $Root "assets"
$index  = Join-Path $Root "AssetIndex.qml"
$tempDir = if ($env:TEMP) { $env:TEMP } else { [System.IO.Path]::GetTempPath() }
$log     = Join-Path $tempDir "unikron-avatar-watch.log"
$exts   = @(".png", ".jpg", ".jpeg", ".webp", ".svg")

function Write-Log([string]$message) {
    $stamp = (Get-Date).ToString("yyyy-MM-dd HH:mm:ss")
    Add-Content -LiteralPath $log -Value "$stamp  $message" -Encoding UTF8
}

function Get-LayerOrder([string]$name) {
    $m = [regex]::Match($name, '^(\d+)[\-_ ]+(.+)$')
    if ($m.Success) { return [int]$m.Groups[1].Value }
    return 1000
}

function Write-Index {
    $lines = New-Object System.Collections.Generic.List[string]
    $lines.Add("import QtQuick 2.15")
    $lines.Add("")
    $lines.Add("// Generated by avatar_tools/watch_art.ps1 - do not edit by hand.")
    $lines.Add("// One entry per folder in assets/, in layer order; files are the images inside.")
    $lines.Add("// Adding art: drop the file in its folder; this file is rewritten for you.")
    $lines.Add("QtObject {")
    $lines.Add("    readonly property var folders: [")

    $dirs = Get-ChildItem -LiteralPath $assets -Directory |
            Where-Object { $_.Name -notmatch '^[_.]' } |
            Sort-Object -Property @{ Expression = { Get-LayerOrder $_.Name } },
                                  @{ Expression = { $_.Name.ToLowerInvariant() } }

    $folderCount = 0
    $imageCount = 0

    foreach ($dir in $dirs) {
        $files = Get-ChildItem -LiteralPath $dir.FullName -File |
                 Where-Object { $exts -contains $_.Extension.ToLowerInvariant() } |
                 Sort-Object -Property @{ Expression = { $_.Name.ToLowerInvariant() } }

        $quoted = @()
        foreach ($file in $files) { $quoted += '"' + $file.Name + '"' }

        $lines.Add('        { "id": "' + $dir.Name + '", "files": [' + ($quoted -join ", ") + '] },')
        $folderCount++
        $imageCount += $files.Count
    }

    $lines.Add("    ]")
    $lines.Add("}")

    $utf8 = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllLines($index, $lines, $utf8)
    Write-Log "wrote AssetIndex.qml: $folderCount categories, $imageCount images"
}

if (-not (Test-Path -LiteralPath $assets)) {
    Write-Log "ERROR: no art folder at $assets"
    exit 1
}

Write-Log "watching $assets"
try { Write-Index } catch { Write-Log "ERROR on first scan: $_" }

if ($Once) { exit 0 }

$watcher = New-Object System.IO.FileSystemWatcher
$watcher.Path = $assets
$watcher.IncludeSubdirectories = $true
$watcher.NotifyFilter = [System.IO.NotifyFilters]::FileName -bor [System.IO.NotifyFilters]::DirectoryName -bor [System.IO.NotifyFilters]::LastWrite
$watcher.EnableRaisingEvents = $true

$global:UniKronPending = $null
$mark = {
    if ($null -eq $global:UniKronPending) { $global:UniKronPending = Get-Date }
}
foreach ($eventName in @("Created", "Deleted", "Renamed", "Changed")) {
    Register-ObjectEvent -InputObject $watcher -EventName $eventName -Action $mark | Out-Null
}

# Debounce: a copy or a delete can fire several events in a row.
while ($true) {
    Start-Sleep -Milliseconds 400
    if ($null -ne $global:UniKronPending -and ((Get-Date) - $global:UniKronPending).TotalSeconds -ge 2) {
        $global:UniKronPending = $null
        try { Write-Index } catch { Write-Log "ERROR: $_" }
    }
}
