#!/usr/bin/env python3
"""Writes assets/AssetIndex.js - the list of category folders and the images in
each one.

The editor cannot list a directory at runtime: Qt.labs.folderlistmodel is not
part of the Pegasus builds, and QML file reads are blocked. So the folder
contents travel with the theme as data, and this script is what produces it.

Run it again after adding or removing art:

    python art_index.py

It is also called automatically at the end of avatar_art.py.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent      # .../avatar
ASSETS = ROOT / "assets"
INDEX = ASSETS / "AssetIndex.js"

IMAGE_SUFFIXES = {".png", ".jpg", ".jpeg", ".webp", ".svg"}

HEADER = """\
.pragma library

// Generated by avatar_tools/art_index.py - do not edit by hand.
// One entry per folder in assets/, in layer order; files are the images inside.
// Adding art: drop the file in its folder and run  python art_index.py
var folders = [
"""


def layer_order(folder_name: str) -> int:
    """Same rule as Style.js: '20_pants' -> 20, 'pants' -> 1000."""
    m = re.match(r"^(\d+)[\-_ ]+(.+)$", folder_name)
    return int(m.group(1)) if m else 1000


def collect() -> list[dict]:
    if not ASSETS.is_dir():
        raise SystemExit(f"no assets folder at {ASSETS}")

    found = []
    for folder in sorted(ASSETS.iterdir(), key=lambda p: p.name.lower()):
        if not folder.is_dir():
            continue
        name = folder.name
        if name.startswith("_") or name.startswith("."):
            continue                                  # _ui and friends are chrome
        files = sorted(
            (f.name for f in folder.iterdir()
             if f.is_file() and f.suffix.lower() in IMAGE_SUFFIXES),
            key=str.lower,
        )
        found.append({"id": name, "files": files})

    found.sort(key=lambda entry: (layer_order(entry["id"]), entry["id"].lower()))
    return found


def write_index(folders: list[dict] | None = None) -> Path:
    folders = collect() if folders is None else folders
    lines = [HEADER]
    for entry in folders:
        files = ", ".join(json.dumps(f) for f in entry["files"])
        lines.append(f'    {{ id: {json.dumps(entry["id"])}, files: [{files}] }},\n')
    lines.append("]\n")
    INDEX.write_text("".join(lines), encoding="utf-8")

    categories = len(folders)
    images = sum(len(e["files"]) for e in folders)
    print(f"wrote {INDEX.relative_to(ROOT)}: {categories} categories, {images} images")
    return INDEX


def main() -> int:
    write_index()
    return 0


if __name__ == "__main__":
    sys.exit(main())
